/// App-wide names. Change them here and every part of the app picks them up.
public enum AppInfo {
    /// Full name, used where there's room (web page title, headings).
    public static let displayName = "Doughn't worry, I left a trail of crumbs"

    /// App Store "Name" field (max 30 characters).
    public static let storeName = "Doughn't Worry"

    /// App Store "Subtitle" field (max 30 characters).
    public static let storeSubtitle = "I left a trail of crumbs"

    /// Name under the home-screen icon (~12 characters show before it's cut off).
    public static let homeScreenName = "Doughn't Worry"
}
